export interface UntitledCatalogIconItem {
  id: string
  name: string
  kebab: string
  category: string
  Icon: UntitledIconComponent
  Component: UntitledIconComponent
}

function toKebabCase(str: string): string {
  return str
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d+)/g, '$1-$2')
    .toLowerCase()
}

function toHumanLabel(str: string): string {
  return str
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/([a-zA-Z])(\d+)/g, '$1 $2')
    .replace(/\b0(\d)\b/g, '$1')
}

function inferIconCategory(name: string): string {
  const lower = name.toLowerCase()
  if (
    lower.includes('arrow') ||
    lower.includes('chevron') ||
    lower.includes('corner') ||
    lower.includes('switch') ||
    lower.includes('refresh') ||
    lower.includes('expand')
  ) {
    return 'Arrows & Navigation'
  }
  if (
    lower.includes('file') ||
    lower.includes('folder') ||
    lower.includes('clipboard') ||
    lower.includes('book') ||
    lower.includes('archive')
  ) {
    return 'Files & Folders'
  }
  if (
    lower.includes('code') ||
    lower.includes('terminal') ||
    lower.includes('git') ||
    lower.includes('cpu') ||
    lower.includes('database') ||
    lower.includes('server') ||
    lower.includes('data') ||
    lower.includes('brackets') ||
    lower.includes('variable')
  ) {
    return 'Development & Tech'
  }
  if (
    lower.includes('bold') ||
    lower.includes('italic') ||
    lower.includes('heading') ||
    lower.includes('align') ||
    lower.includes('type') ||
    lower.includes('list') ||
    lower.includes('pen') ||
    lower.includes('edit') ||
    lower.includes('table')
  ) {
    return 'Editor & Formatting'
  }
  if (
    lower.includes('alert') ||
    lower.includes('check') ||
    lower.includes('info') ||
    lower.includes('help') ||
    lower.includes('bell') ||
    lower.includes('shield') ||
    lower.includes('lock')
  ) {
    return 'Alerts & Security'
  }
  if (
    lower.includes('message') ||
    lower.includes('mail') ||
    lower.includes('annotation') ||
    lower.includes('phone') ||
    lower.includes('send') ||
    lower.includes('share')
  ) {
    return 'Communication'
  }
  if (
    lower.includes('calendar') ||
    lower.includes('clock') ||
    lower.includes('alarm') ||
    lower.includes('sun') ||
    lower.includes('moon') ||
    lower.includes('cloud')
  ) {
    return 'Time & Weather'
  }
  return 'General UI'
}

