export function getUntitledIconByName(nameOrKebab: string): UntitledCatalogIconItem | null {
  const clean = nameOrKebab.trim().toLowerCase()
  if (!clean) return null
  const direct = ALL_ICON_MAP.get(clean)
  if (direct) return direct
  const normalized = clean.replace(/[-_\s]+/g, '')
  for (const item of ALL_UNTITLED_UI_ICONS) {
    if (item.id.toLowerCase() === normalized) return item
  }
  const with01 = ALL_ICON_MAP.get(`${clean}-01`) || ALL_ICON_MAP.get(`${normalized}01`)
  if (with01) return with01
  return null
}

export function searchUntitledIcons(query: string, limit = 96): UntitledCatalogIconItem[] {
  const q = query.trim().toLowerCase()
  if (!q) {
    const featured: UntitledCatalogIconItem[] = []
    for (const id of FEATURED_ICON_IDS) {
      const found = getUntitledIconByName(id)
      if (found && !featured.includes(found)) {
        featured.push(found)
      }
    }
    for (const item of ALL_UNTITLED_UI_ICONS) {
      if (featured.length >= limit) break
      if (!featured.includes(item)) featured.push(item)
    }
    return featured.slice(0, limit)
  }

  const scored: Array<{ item: UntitledCatalogIconItem; score: number }> = []
  for (const item of ALL_UNTITLED_UI_ICONS) {
    const idLower = item.id.toLowerCase()
    const nameLower = item.name.toLowerCase()
    const kebabLower = item.kebab.toLowerCase()
    const catLower = item.category.toLowerCase()

    if (idLower === q || kebabLower === q) {
      scored.push({ item, score: 100 })
    } else if (idLower.startsWith(q) || kebabLower.startsWith(q) || nameLower.startsWith(q)) {
      scored.push({ item, score: 80 })
    } else if (idLower.includes(q) || kebabLower.includes(q) || nameLower.includes(q)) {
      scored.push({ item, score: 60 })
    } else if (catLower.includes(q)) {
      scored.push({ item, score: 30 })
    }
  }

  scored.sort((a, b) => b.score - a.score || a.item.name.localeCompare(b.item.name))
  return scored.slice(0, limit).map((s) => s.item)
}
